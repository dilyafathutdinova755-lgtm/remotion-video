#!/usr/bin/env node
/**
 * Готовит текст для TTS (ElevenLabs): заменяет арабские цифры русскими
 * словами, чтобы озвучка не читала «6» как отдельные символы, а говорила
 * «шесть». Ничего, кроме цифр, не трогает — на видео (task_data,
 * condition_text, task_number, отображаемые числа) эта функция вообще не
 * влияет, она применяется только к копии текста, которая уходит в TTS.
 *
 * Что специально НЕ трогаем (см. PROTECTED_ADJACENT ниже):
 *   - химические формулы и переменные («C5H11OH», «x2», «2x») — цифра,
 *     стоящая вплотную к букве (любого алфавита) с любой стороны, не
 *     конвертируется;
 *   - дроби («3/4») и степени («x^2») — цифра рядом с «/» или «^» тоже не
 *     трогается;
 *   - проценты («15%») — цифра перед «%» не трогается;
 *   - десятичные дроби («3,5» / «3.14») — «.» и «,» тоже входят в защищённые
 *     соседние символы, так что обе половины остаются цифрами: превращать
 *     дробь в «три целых пять десятых» эта функция не умеет и не должна —
 *     лучше нетронутая цифра, чем неверно прочитанная дробь;
 *   - число, уже записанное словом («шестого», «двадцать пять») — цифр в
 *     нём просто нет, регулярка на \d+ его не находит, дублирования не
 *     возникает в принципе.
 *
 * Ограничение (сознательное, не баг): согласование рода/падежа не
 * учитывается — «2» всегда «два», а не «две». Из примеров в задании этого
 * не требовалось (все числа либо не имеют родовых форм, либо это счёт
 * заданий/значений, для которых «два» — стандартная форма); там, где
 * реально нужна форма «две» (например, «2 книги»), результат будет
 * грамматически неточным — это стоит поправить в самом тексте, а не в этой
 * функции, которая не разбирает синтаксис вокруг числа.
 */

const ONES = [
  "",
  "один",
  "два",
  "три",
  "четыре",
  "пять",
  "шесть",
  "семь",
  "восемь",
  "девять",
];
const TEENS = [
  "десять",
  "одиннадцать",
  "двенадцать",
  "тринадцать",
  "четырнадцать",
  "пятнадцать",
  "шестнадцать",
  "семнадцать",
  "восемнадцать",
  "девятнадцать",
];
const TENS = [
  "",
  "",
  "двадцать",
  "тридцать",
  "сорок",
  "пятьдесят",
  "шестьдесят",
  "семьдесят",
  "восемьдесят",
  "девяносто",
];
const HUNDREDS = [
  "",
  "сто",
  "двести",
  "триста",
  "четыреста",
  "пятьсот",
  "шестьсот",
  "семьсот",
  "восемьсот",
  "девятьсот",
];

/** Русское склонение по числу: forms = [1 (один), 2-4 (два), 5+ (пять)]. */
const pluralRu = (n, forms) => {
  const mod10 = n % 10;
  const mod100 = n % 100;
  if (mod100 >= 11 && mod100 <= 14) return forms[2];
  if (mod10 === 1) return forms[0];
  if (mod10 >= 2 && mod10 <= 4) return forms[1];
  return forms[2];
};

/** 0-999 словами. feminine — для «тысячи» («одна», «две», а не «один», «два»). */
const threeDigitsToWords = (n, feminine = false) => {
  const words = [];
  const h = Math.floor(n / 100);
  const rem = n % 100;
  if (h) words.push(HUNDREDS[h]);
  if (rem >= 10 && rem < 20) {
    words.push(TEENS[rem - 10]);
  } else {
    const t = Math.floor(rem / 10);
    const o = rem % 10;
    if (t) words.push(TENS[t]);
    if (o) {
      if (feminine && o === 1) words.push("одна");
      else if (feminine && o === 2) words.push("две");
      else words.push(ONES[o]);
    }
  }
  return words;
};

/** Целое число (строкой или числом) → кириллические слова, именительный падеж. */
export const numberToRussianWords = (value) => {
  let n = typeof value === "string" ? parseInt(value, 10) : value;
  if (!Number.isFinite(n)) return String(value);
  if (n === 0) return "ноль";

  const negative = n < 0;
  n = Math.abs(n);

  const parts = [];
  const millions = Math.floor(n / 1_000_000);
  n %= 1_000_000;
  const thousands = Math.floor(n / 1000);
  n %= 1000;
  const rest = n;

  if (millions) {
    parts.push(...threeDigitsToWords(millions));
    parts.push(pluralRu(millions, ["миллион", "миллиона", "миллионов"]));
  }
  if (thousands) {
    parts.push(...threeDigitsToWords(thousands, true));
    parts.push(pluralRu(thousands, ["тысяча", "тысячи", "тысяч"]));
  }
  if (rest || parts.length === 0) {
    parts.push(...threeDigitsToWords(rest));
  }

  return (negative ? "минус " : "") + parts.join(" ");
};

// Символы, при соседстве с которыми "голое" число не трогаем: буквы любого
// алфавита (формулы, переменные), "/" (дроби), "^" (степени), "%" (проценты).
// Точка и запятая сюда НЕ входят — иначе обычная точка в конце предложения
// («задание 7.») ложно приняла бы число за половину десятичной дроби и
// заблокировала конвертацию. Десятичные дроби ловятся отдельной веткой
// регулярки ниже (\d+[.,]\d+) ДО обычных чисел, поэтому до одиночного «7»
// в «7.» дело просто не доходит с этой проблемой.
const PROTECTED_ADJACENT = /[\p{L}/^%]/u;
// Сначала пробуем десятичную дробь целиком (3.14, 3,5) — она не трогается;
// иначе — просто число.
const TOKEN_RE = /\d+[.,]\d+|\d+/gu;

/** Заменяет «голые» числа словами; формулы/переменные/дроби/проценты не трогает. */
export const normalizeForVoiceover = (text) => {
  const s = String(text);
  return s.replace(TOKEN_RE, (match, offset) => {
    if (/[.,]/.test(match)) return match; // десятичная дробь — не разбираем

    const before = s[offset - 1];
    const after = s[offset + match.length];
    if (
      (before && PROTECTED_ADJACENT.test(before)) ||
      (after && PROTECTED_ADJACENT.test(after))
    ) {
      return match;
    }
    return numberToRussianWords(match);
  });
};
