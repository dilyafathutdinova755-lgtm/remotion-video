import { COLORS } from "../theme";
import { w } from "./dsl";
import type { TaskDef } from "./types";

/**
 * Задание 8 ОГЭ по русскому языку: раскрыть слово в скобках и поставить
 * его в нужную форму по контексту — числительные в косвенных падежах,
 * степени сравнения прилагательных, формы местоимений, повелительное
 * наклонение глагола и т. п.
 *
 * Как и у остальных заданий по русскому языку (лексика-6, форма слова-7),
 * пошагового разбора здесь нет: правило либо знаешь, либо нет — считать
 * нечего. Пошаговый разбор в проекте оставлен только предметам, где есть
 * реальный счёт или вывод формулы (математика, физика, химия, биология);
 * у русского языка и истории ответ виден сразу, с пояснением одним блоком
 * под ним. Розовая палитра — она же у русского-7 и истории.
 *
 * Первый предмет в проекте под брендом ОГЭ, а не ЕГЭ — `examType: "oge"`
 * переключает логотип и первую часть плашки хука на «ОГЭ» (см.
 * `AppLogo.tsx`, `Watermark.tsx`, `HookScene.tsx`); во всём остальном
 * (палитра, тайминг, шрифты, безопасные зоны) система та же самая.
 */

const SUBJECT = "в ОГЭ по русскому языку";
const NOTE = { color: COLORS.textMuted } as const;

const INSTRUCTION =
  "Раскройте скобки и запишите слово в соответствии с нормами современного русского литературного языка.";

type Oge8Spec = {
  id: string;
  hook: string[];
  /** Условие со словом в скобках, капсом, как в бланке. */
  sentence: string;
  /** Слово в скобках без изменений — то, что показано слева от стрелки в ответе. */
  bracketed: string;
  /** Верная форма — сам ответ. */
  answer: string;
  /** Пояснение — по строке на мысль. */
  why: string[];
  problemSize?: number;
};

const makeOge8Task = (spec: Oge8Spec): TaskDef => ({
  id: spec.id,
  number: 8,
  examType: "oge",
  subject: SUBJECT,
  palette: "pink",
  hook: spec.hook,
  pillLabel: "Задание",
  instruction: INSTRUCTION,

  tokens: w(spec.sentence),
  problemSize: spec.problemSize ?? 46,

  // Правило либо знаешь, либо нет — разбирать по шагам нечего
  solutions: [],
  answerSeconds: 11,

  answerLead: "Верная форма",
  answerFormula: (
    <>
      <span style={NOTE}>{spec.bracketed}</span>
      <span style={{ margin: "0 20px", color: COLORS.accentLine }}>→</span>
      <span style={{ color: COLORS.accent }}>{spec.answer}</span>
    </>
  ),
  answer: spec.answer,
  check: (
    <>
      {spec.why.map((sentence, i) => (
        <div key={i}>{sentence}</div>
      ))}
    </>
  ),
});

