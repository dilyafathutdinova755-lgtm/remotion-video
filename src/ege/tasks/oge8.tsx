import { line, card, makeSolution } from "../Solution";
import type { SolutionItem } from "../Solution";
import { COLORS } from "../theme";
import { w } from "./dsl";
import type { TaskDef } from "./types";

/**
 * Задание 8 ОГЭ по русскому языку: раскрыть слово в скобках и поставить
 * его в нужную форму по контексту — числительные в косвенных падежах,
 * степени сравнения прилагательных, формы местоимений, повелительное
 * наклонение глагола и т. п.
 *
 * Разбор короткий, в один-два шага: что за форма нужна по контексту → как
 * она образуется у этого слова. Последний шаг сам заканчивается ответом —
 * отдельной сцены ответа нет (`answerRecap: false`), как у простых
 * предметов без длинного счёта (математика, физика).
 *
 * Первый предмет в проекте под брендом ОГЭ, а не ЕГЭ — `examType: "oge"`
 * переключает логотип и первую часть плашки хука на «ОГЭ» (см.
 * `AppLogo.tsx`, `Watermark.tsx`, `HookScene.tsx`); во всём остальном
 * (палитра, тайминг, шрифты, безопасные зоны) система та же самая.
 */

const SUBJECT = "в ОГЭ по русскому языку";
const ACCENT = { color: COLORS.accent, fontWeight: 700 } as const;
const NOTE = { color: COLORS.textMuted } as const;

const INSTRUCTION =
  "Раскройте скобки и запишите слово в соответствии с нормами современного русского литературного языка.";

const base = (id: string, hook: string[], problemSize = 46) => ({
  id,
  number: 8,
  examType: "oge" as const,
  subject: SUBJECT,
  palette: "blue" as const,
  hook,
  pillLabel: "Задание",
  instruction: INSTRUCTION,
  problemSize,
  // Последний шаг разбора сам заканчивается ответом
  answerRecap: false,
});

const step = (n: string, title: string, seconds: number, items: SolutionItem[]) => ({
  seconds,
  Component: makeSolution({ step: n, title, seconds, items }),
});

/** Хвост последнего шага: сам ответ крупной акцентной карточкой + строка пояснения. */
const finish = (answer: string, note: string): SolutionItem[] => [
  card(<span style={ACCENT}>{answer}</span>, { accent: true, size: 56 }),
  line(<span style={NOTE}>{note}</span>),
];

