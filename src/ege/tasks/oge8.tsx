export const oge8Chetyresta: TaskDef = {
  ...base("Oge8Chetyresta", ["ЧЕТЫРЕСТА книгами", "как правильно?"], 44),

  tokens: w(
    "(ЧЕТЫРЕСТА) книгами заставили весь новый стеллаж библиотеки.",
  ),

  solutions: [
    step("1", "Какое это числительное", 6.5, [
      line(<>Четыреста — сложное числительное: складывается из двух простых.</>),
      card(<>четыреста = четыре + сто</>, { size: 42 }),
    ]),
    step("2", "Склоняются обе части", 6.5, [
      line(<>В творительном падеже меняется и «четыре», и «сто»:</>),
      ...finish(
        "четырьмястами",
        "Как у простых пятисотен — обе части сложного числительного склоняются вместе.",
      ),
    ]),
  ],

  answer: "четырьмястами",
};

