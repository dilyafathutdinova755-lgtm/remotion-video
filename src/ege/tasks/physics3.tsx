/**
 * Задание 3 ЕГЭ по физике: энергия, импульс, движение по наклонной.
 *
 * Разбор рассчитан на того, кто тему не знает: каждая формула сначала
 * объясняется словами, и отдельно проговаривается, почему масса сокращается
 * или почему высота — это не длина склона. Ускорение свободного падения
 * везде 10 м/с², как и просят в условии.
 *
 * Отдельной сцены с ответом нет: последний шаг и есть ответ.
 */

const SUBJECT = "в ЕГЭ по физике";
const ACCENT = { color: COLORS.accent, fontWeight: 700 } as const;
const NOTE = { color: COLORS.textMuted } as const;

const base = (
  id: string,
  hook: string[],
  illustration: string | string[],
  problemSize = 44,
) => ({
  id,
  illustration,
  number: 3,
  subject: SUBJECT,
  hook,
  problemSize,
  answerRecap: false,
});

const step = (
  n: string,
  title: string,
  seconds: number,
  items: SolutionItem[],
) => ({
  seconds,
  Component: makeSolution({ step: n, title, seconds, items }),
});

/** Хвост последнего шага: сам ответ и строчка проверки под ним. */
const finish = (answer: ReactNode, note: string): SolutionItem[] => [
  card(answer, { accent: true, size: 46 }),
  line(<span style={NOTE}>{note}</span>),
];

