export const snail: TaskDef = {
  ...base("Bio3Snail", "24 хромосомы. А в гамете?", 48),

  tokens: w(
    "В соматической клетке виноградной улитки 24 хромосомы. Какой набор хромосом имеют гаметы этого животного? В ответе запишите только количество хромосом.",
  ),

  solutions: [
    step("1", "Что за клетка", 7, [
      line(<>Соматическая клетка — это тело, набор в ней двойной:</>),
      card(<>2n = 24</>, { size: 48 }),
    ]),
    step("2", "Переходим к гамете", 7, [
      line(<>Гаметы образуются мейозом, набор уменьшается вдвое:</>),
      card(
        <span>
          n = 24 : 2 = <span style={ACCENT}>12</span>
        </span>,
        { accent: true, size: 46 },
      ),
    ]),
  ],

  answerLead: "В гамете улитки",
  answerFormula: <>2n = 24 → n = 12</>,
  answer: "12",
  unit: "хромосом",
  check: why(
    "Соматическая клетка — двойной набор, гамета — половина от него.",
    "24 : 2 = 12, а при оплодотворении 12 + 12 снова дадут 24.",
  ),
};

