/**
 * Задание 3 ЕГЭ по биологии: хромосомные наборы и подсчёты по ДНК.
 *
 * Считать почти нечего — весь вопрос в том, какая клетка перед нами и что
 * именно спрашивают. Поэтому первый шаг всегда про это, а второй — само
 * действие. Ролики идут на зелёной палитре, её включает subject.
 */

const SUBJECT = "в ЕГЭ по биологии";
const ACCENT = { color: COLORS.accent, fontWeight: 700 } as const;

const base = (id: string, hook: string[], problemSize = 48) => ({
  id,
  number: 3,
  subject: SUBJECT,
  palette: "green" as const,
  hook,
  pillLabel: "Задание",
  problemSize,
  // Пояснение к ответу надо успеть прочитать
  answerSeconds: 9,
});

/** Как пришли к ответу: коротко, по строке на мысль. */
const why = (...lines: string[]) => (
  <>
    {lines.map((text, i) => (
      <div key={i}>{text}</div>
    ))}
  </>
);

const step = (
  n: string,
  title: string,
  seconds: number,
  items: SolutionItem[],
) => ({
  seconds,
  Component: makeSolution({ step: n, title, seconds, items }),
});

