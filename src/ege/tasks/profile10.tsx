/**
 * Задание 10 ЕГЭ по профильной математике: текстовые задачи на движение,
 * работу, смеси и прогрессии.
 *
 * Отдельной сцены с ответом здесь нет: последний шаг разбора и есть ответ,
 * повторять его следующим кадром — дублирование. Поэтому каждый второй шаг
 * заканчивается акцентной карточкой с ответом и короткой проверкой.
 */

const SUBJECT = "в ЕГЭ по профильной математике";
const ACCENT = { color: COLORS.accent, fontWeight: 700 } as const;
const NOTE = { color: COLORS.textMuted } as const;

const base = (
  id: string,
  hook: string[],
  illustration: string,
  problemSize = 44,
) => ({
  id,
  illustration,
  number: 10,
  subject: SUBJECT,
  hook,
  problemSize,
  // Разбор уже привёл к ответу — отдельной сцены с повтором нет
  answerRecap: false,
});

const step = (
  n: string,
  title: string,
  seconds: number,
  items: SolutionItem[],
) => ({
  seconds,
  Component: makeSolution({ step: n, title, seconds, items }),
});

/** Хвост последнего шага: сам ответ и строчка проверки под ним. */
const finish = (answer: ReactNode, note: string): SolutionItem[] => [
  card(answer, { accent: true, size: 46 }),
  line(<span style={NOTE}>{note}</span>),
];

