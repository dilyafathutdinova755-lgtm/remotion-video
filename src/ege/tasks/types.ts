import type { ReactNode } from "react";
import type { PaletteName } from "../theme";

/** Кусок условия — слово. */
export type Token = string;

/** Сцена решения: сколько секунд держится и что рисует. */
export type SolutionScene = {
  seconds: number;
  Component: React.FC;
};

/**
 * Тайминг сцен по реальной озвучке вместо оценки по числу слов. Секунды —
 * абсолютные, от начала аудиофайла. Опционально: только у задач, для
 * которых прислали и разметили озвучку (см. PLAYBOOK.md).
 */
export type AudioSync = {
  /** Путь к файлу в public/, без ведущего слэша — для staticFile(). */
  src: string;
  /** Полная длительность аудио в секундах — определяет длину ролика. */
  totalSec: number;
  /** Секунда начала сцены условия (хук — с нуля до этой секунды). */
  conditionSec: number;
  /** Секунда начала каждой сцены-шага разбора, по порядку. */
  stepSec: number[];
  /**
   * Секунда начала сцены ответа/понятия — только когда она есть отдельно от
   * шагов разбора (задание 19 по истории: шагов нет вовсе, `stepSec: []`, и
   * без этого поля вся озвучка ответа ошибочно попадала бы в сцену условия).
   * У математики она не нужна: там ответ — последняя реплика последнего
   * шага (см. `stepBeats`), а не отдельная сцена.
   */
  answerSec?: number;
  /**
   * Секунда, с которой в сцене-понятии начинается блок «Факт» — вторая
   * реплика внутри той же сцены, после блока «Смысл понятия». Абсолютная,
   * как и остальные поля; `ConceptScene` переводит её в кадр относительно
   * начала своей сцены (`factAtSec - answerSec`).
   */
  factAtSec?: number;
  /** Секунда начала финального экрана. */
  outroSec: number;
  /**
   * Шаги, где озвучка идёт двумя-тремя репликами подряд (например,
   * решение — отдельно от ответа): сколько пунктов `SolutionItem` относится
   * к каждой реплике и во сколько секунд от начала этого шага начинается
   * вторая (третья…) реплика. Индекс объекта — индекс шага в `solutions`.
   * Первая реплика всегда начинается с начала шага, поэтому в `atSec` она
   * не указывается — только следующие.
   */
  stepBeats?: Record<number, { itemCounts: number[]; atSec: number[] }>;
};

/** Всё, что есть у любой задачи независимо от того, чем она заканчивается. */
type TaskCommon = {
  /** id композиции Remotion, например "Task10". */
  id: string;
  /** Номер задания в ЕГЭ. */
  number: number;

  /** Предмет — строка под заголовком. По умолчанию профильная математика. */
  subject?: string;
  /** Палитра ролика. Не задана — синяя. */
  palette?: PaletteName;
  /**
   * Вопрос на хук-кадре в первые секунды ролика. Массив — это строки:
   * переносы задаются вручную, чтобы на первой строке не оставались
   * хвосты вроде «8. А».
   */
  hook?: string | string[];
  /** Надпись на плашке над условием. */
  pillLabel?: string;

  /**
   * Формулировка задания над самим условием. У математики её нет — там
   * задача и есть формулировка; у русского это отдельная строка вида
   * «Отредактируйте предложение…».
   */
  instruction?: string;

  /** Условие, разбитое на слова. */
  tokens: Token[];
  /**
   * Варианты списком вместо сплошного условия: у задания 7 по русскому это
   * пять словосочетаний, и читать их вслух не надо — их разглядывают.
   */
  options?: string[];
  /** Кегль условия — длинные тексты набираем мельче, чтобы влезали. */
  problemSize: number;
  /**
   * Картинка под условием: имя файла из public/illustrations без расширения.
   * Список — если по ходу условия появляются разные предметы: картинки
   * сменяют друг друга, поделив сцену поровну.
   *
   * Только по теме задачи — подсказывать ответ она не должна.
   */
  illustration?: string | string[];

  /** Пошаговый разбор. У коротких заданий его может не быть вовсе. */
  solutions: SolutionScene[];

  /**
   * Повторять ли ответ отдельной сценой. У задач с разбором это дублирование:
   * последний шаг уже приводит к ответу, и повтор ничего не добавляет.
   *
   * Поле переходное. Остальные предметы с разбором переедут на `false`, когда
   * их будут перерендеривать: сейчас их пояснение живёт в `check`, и убрать
   * сцену, не перенеся пояснение в последний шаг, значит его потерять.
   */
  answerRecap?: boolean;

  /** Длительность финальной сцены: если разбора нет, ей нужно больше времени. */
  answerSeconds?: number;

  /**
   * Тайминг по реальной озвучке вместо оценки по числу слов. См. `AudioSync`.
   * Не задан — сцены считаются по-старому, длительность на глаз/по словам.
   */
  audioSync?: AudioSync;
};

/** Ответ-значение: число или слово, которое вписывают в бланк. */
type ValueAnswer = {
  /** Подводка над формулой ответа. */
  answerLead?: string;
  /** Как получился ответ. У заданий на форму слова считать нечего. */
  answerFormula?: ReactNode;
  /**
   * Неверный вариант из условия. Рисуется зачёркнутым — иначе читается как
   * продолжение ответа.
   */
  wrongNote?: ReactNode;
  /** Сам ответ. */
  answer: string;
  /** Единицы измерения; у ответа-слова их нет. */
  unit?: string;
  /** Кегль ответа. Не задан — считается из длины слова. */
  answerSize?: number;
  /** Строчка проверки под ответом. */
  check?: ReactNode;
  concept?: undefined;
};

/**
 * Ответ-текст: задание 19 по истории просит не значение, а два абзаца —
 * смысл понятия и факт, который его конкретизирует.
 */
type ConceptAnswer = {
  concept: {
    definition: ReactNode;
    fact: ReactNode;
  };
};

/**
 * Полное описание задачи. Всё, что меняется от ролика к ролику, живёт
 * здесь; сцены забирают это из контекста и остаются общими.
 */
export type TaskDef = TaskCommon & (ValueAnswer | ConceptAnswer);

/** Задача с ответом-значением: сцена ответа работает только с такими. */
export type ValueTask = TaskCommon & ValueAnswer;

/**
 * Кегль ответа: длинное слово вроде «преследовало» в 132 пункта не влезает
 * по ширине кадра, поэтому размер подбирается по числу знаков.
 */
export const answerFontSize = (task: ValueTask): number =>
  task.answerSize ??
  Math.min(132, Math.floor(1111 / Math.max(task.answer.length, 1)));
