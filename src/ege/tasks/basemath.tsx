/**
 * Задание 1 ЕГЭ по базовой математике: одно-два действия на пропорцию,
 * перевод единиц или стоимость.
 *
 * Разбор пошаговый, но шагов ровно два и держатся они недолго — считать
 * тут нечего, важно не пропустить второе действие. Именно на нём чаще
 * всего и теряют балл: посчитали расход, а умножить на цену забыли.
 */

const SUBJECT = "в ЕГЭ по базовой математике";
const ACCENT = { color: COLORS.accent, fontWeight: 700 } as const;

/** Общая часть описания: предмет, номер задания, кегль условия. */
const base = (id: string, hook: string[], problemSize = 48) => ({
  id,
  number: 1,
  subject: SUBJECT,
  hook,
  pillLabel: "Задание",
  problemSize,
  answerSeconds: 6,
});

/** Шаг разбора: короткий, на одно действие. */
const step = (
  n: string,
  title: string,
  seconds: number,
  items: SolutionItem[],
) => ({
  seconds,
  Component: makeSolution({ step: n, title, seconds, items }),
});

// --- счётчик воды: две задачи, отличаются показаниями и ценой ---------------

/**
 * Ошибка здесь одна и та же: платят за разность показаний, а не за само
 * показание счётчика.
 */
const makeWaterTask = (
  id: string,
  name: string,
  gender: "м" | "ж",
  place: string,
  kind: "горячей" | "холодной",
  month: string,
  monthIn: string,
  from: string,
  to: string,
  was: number,
  now: number,
  rub: number,
  kop: number,
  answer: string,
): TaskDef => {
  const spent = now - was;
  const price = rub + kop / 100;
  const должен = gender === "ж" ? "должна заплатить" : "должен заплатить";

  return {
    ...base(id, ["Сколько платить", "за воду?"], 44),

    tokens: w(
      `В ${place}, где проживает ${name}, ${from} счётчик ${kind} воды показывал ${was} куб. м, а ${to} — ${now} куб. м. Какую сумму ${должен} ${name} за ${kind} воду за ${monthIn}, если цена 1 куб. м ${kind} воды составляет ${rub} руб. ${kop} коп.? Ответ дайте в рублях.`,
    ),

    solutions: [
      step("1", "Считаем расход", 7, [
        line(<>Платят за разность показаний, а не за само показание:</>),
        card(
          <>
            {now} − {was} = {spent} куб. м
          </>,
          { size: 44 },
        ),
      ]),
      step("2", "Умножаем на цену", 7, [
        line(
          <>
            {rub} руб. {kop} коп. — это {String(price).replace(".", ",")} руб.:
          </>,
        ),
        card(
          <span>
            {spent} · {String(price).replace(".", ",")} ={" "}
            <span style={ACCENT}>{answer}</span> руб.
          </span>,
          { accent: true, size: 44 },
        ),
      ]),
    ],

    answerLead: `За ${month} набежало`,
    answerFormula: (
      <>
        {spent} куб. м · {String(price).replace(".", ",")} руб.
      </>
    ),
    answer,
    unit: "рублей",
    check: <>счётчик накопительный: за месяц потрачено {spent} куб. м</>,
  };
};

