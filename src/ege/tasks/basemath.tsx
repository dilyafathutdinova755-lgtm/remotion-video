// --- принтер: две задачи, отличаются скоростью и временем --------------------

/** Минуты переводим в секунды и делим — иначе единицы не сойдутся. */
const makePrinterTask = (
  id: string,
  perPage: number,
  minutes: number,
  answer: number,
): TaskDef => {
  const seconds = minutes * 60;

  return {
    ...base(id, ["Сколько страниц", "успеет принтер?"], 46),

    tokens: w(
      `Принтер печатает одну страницу за ${perPage} секунд. Какое наибольшее количество страниц можно напечатать на этом принтере за ${minutes} минут?`,
    ),

    solutions: [
      step("1", "Переводим в секунды", 6.5, [
        line(<>Скорость дана в секундах, время — в минутах:</>),
        card(
          <>
            {minutes} · 60 = {seconds} с
          </>,
          { size: 46 },
        ),
      ]),
      step("2", "Делим на страницу", 6.5, [
        line(<>Сколько раз по {perPage} секунд помещается в это время:</>),
        card(
          <span>
            {seconds} : {perPage} = <span style={ACCENT}>{answer}</span>
          </span>,
          { accent: true, size: 48 },
        ),
      ]),
    ],

    answerLead: "Принтер напечатает",
    answerFormula: (
      <>
        {seconds} с : {perPage} с
      </>
    ),
    answer: String(answer),
    unit: "страниц",
    check: (
      <>
        проверка: {answer} · {perPage} = {seconds} с — ровно {minutes} минут
      </>
    ),
  };
};

