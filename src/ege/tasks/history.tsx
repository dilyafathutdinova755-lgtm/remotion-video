/**
 * Задание 19 ЕГЭ по истории: раскрыть смысл понятия и привести факт.
 *
 * Разбора по шагам здесь нет и быть не может — задание проверяет знание, а не
 * ход рассуждения. Поэтому после условия сразу идёт финальная сцена с двумя
 * подписанными блоками: «Смысл понятия» и «Факт».
 *
 * Хук у всех роликов один. Спрашивать на титульном кадре что-то своё для
 * каждого понятия бессмысленно: сам вопрос задания и есть «что это такое»,
 * и частный вопрос выдал бы ответ раньше времени.
 */

const HOOK = "Знаешь, что это за понятие?";

/**
 * Формулировка задания одна на все ролики, поэтому уходит в серую строку над
 * понятием, а само понятие набирается крупно — оно здесь и есть условие.
 */
const INSTRUCTION =
  "Раскройте смысл понятия. Приведите один исторический факт, конкретизирующий это понятие. Факт не должен повторять определение.";

const makeConceptTask = (
  id: string,
  term: string,
  definition: React.ReactNode,
  fact: React.ReactNode,
  seconds: number,
  problemSize = 78,
): TaskDef => ({
  id,
  number: 19,
  subject: "в ЕГЭ по истории",
  hook: HOOK,
  pillLabel: "Задание",
  instruction: INSTRUCTION,

  tokens: w(term),
  problemSize,

  // Разбирать по шагам нечего: задание на знание, а не на рассуждение
  solutions: [],
  answerSeconds: seconds,

  concept: { definition, fact },
});

