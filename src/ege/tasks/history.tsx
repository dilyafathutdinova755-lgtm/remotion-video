/**
 * Задание 19 ЕГЭ по истории: раскрыть смысл понятия и привести факт.
 *
 * Разбора по шагам здесь нет и быть не может — задание проверяет знание, а не
 * ход рассуждения. Поэтому после условия сразу идёт финальная сцена с двумя
 * подписанными блоками: «Смысл понятия» и «Факт».
 *
 * Хук — само понятие крупным текстом (а не общий вопрос вроде «Знаешь, что
 * это?»): человек должен успеть на титульном кадре понять, знает он это
 * слово или нет, и решить, смотреть ролик дальше или пролистнуть. Это не
 * нарушает правило «хук не выдаёт ответ» (§7 плейбука) — ответ здесь не
 * само понятие, а его смысл и факт; понятие — это условие, оно и так
 * появляется следующим кадром.
 *
 * У большинства понятий хук — просто само понятие одной строкой (мера
 * derived по умолчанию). Длинные многословные понятия ломаются на строки
 * вручную через `hookLines`, иначе автоперенос HookScene порвёт их не там,
 * где нужно (см. CONVENTIONS.md про перенос хука).
 */

/**
 * Формулировка задания одна на все ролики, поэтому уходит в серую строку над
 * понятием, а само понятие набирается крупно — оно здесь и есть условие.
 */
