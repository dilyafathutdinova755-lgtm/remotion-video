/**
 * Локальные fps-осознанные аналоги f30()/Reveal()/SolutionLayout() из
 * timing.ts/MathBits.tsx/SolutionLayout.tsx — СОЗНАТЕЛЬНО НЕ переиспользуют
 * оригиналы напрямую.
 *
 * Причина: f30() (timing.ts) считает кадры через ОБЩИЙ модульный VIDEO.fps
 * (=60), а не через реальный fps текущей композиции из useVideoConfig().
 * Для всех существующих роликов это незаметно, потому что они ВСЕ рендерятся
 * на VIDEO.fps. Но biology-steps-v1 рендерится на task.renderFps (120)
 * — если бы сцены этого контракта импортировали f30()/Reveal() как есть,
 * все анимации (появление строк, затухание, пружины) шли бы вдвое быстрее
 * реального времени, чем задумано (см. отчёт по фиксу №4: "проверить
 * анимации на 120, отсутствие жёстких констант 30/60 для таймингов").
 *
 * Решение — параметризовать тот же "авторский 30fps-эквивалент", что и
 * f30(), явным fps (который сцены берут из useVideoConfig(), а НЕ из
 * VIDEO.fps), не трогая сам timing.ts: f30()/sec() там остаются чистыми
 * функциями без хуков (это необходимо — totalFramesFor() вызывает их ДО
 * того, как существует RemotionContext, при вычислении durationInFrames
 * для <Composition>, так что превратить их в хуки нельзя).
 */
export const fAt = (fps: number, frames30: number): number =>
  Math.round((frames30 * fps) / 30);
